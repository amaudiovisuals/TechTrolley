const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const compiled = ts.transpileModule(fs.readFileSync('inventoryHelpers.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const context = { exports: {} }; vm.runInNewContext(compiled, context);
const { resolveInventoryScan, supplierInventoryRows, importOutcome, inventoryOwnerSections, overlappingSupplierSources } = context.exports;
const normalize = value => String(value || '').toUpperCase().replace(/[^A-Z0-9#\-_.]/g, '');
const main = { id: '1', sku: 'MODEL', barcode: 'MAIN-QR', serialNumber: 'MAIN-SERIAL' };
const supplier = { id: '2', sku: 'MODEL', barcode: 'AM-QR', serialNumber: 'AM-SERIAL', subrental_company: 7 };
assert.equal(resolveInventoryScan([main, supplier], 'AM-QR', normalize).asset.id, '2');
assert.equal(resolveInventoryScan([main, supplier], 'MODEL', normalize).ambiguous, true);
assert.equal(resolveInventoryScan([supplier, main], 'MODEL', normalize).ambiguous, true);
assert.equal(resolveInventoryScan([main, supplier], 'am-qr', normalize).asset.id, '2');
assert.equal(resolveInventoryScan([main, supplier], 'MISSING', normalize).asset, null);
assert.equal(resolveInventoryScan([main, supplier], '', normalize).asset, null);
assert.equal(resolveInventoryScan([main, supplier], 'MAIN-QR, AM-QR', normalize).ambiguous, true);
assert.equal(resolveInventoryScan([supplier, supplier], 'AM-QR', normalize).asset.id, '2');
assert.equal(supplierInventoryRows([supplier], 7).length, 1);
assert.throws(() => supplierInventoryRows({ results: [supplier], next: 'page2' }, 7));
assert.throws(() => supplierInventoryRows([main], 7));
assert.equal(supplierInventoryRows([{ ...supplier, is_temporary: true }], 7).length, 0);
assert.equal(importOutcome({ created: 0, errors: ['Row failed'] }, true).success, false);
assert.equal(importOutcome({ created: 1, updated: 0, skipped: 0 }, true).success, true);
assert.equal(importOutcome({ created: 1, error: 'Failed' }, false).success, false);
const sections = inventoryOwnerSections([supplier, main, { ...supplier, id: '3', subrental_company: 8 }]);
assert.equal(sections.length, 3);
assert.equal(sections[0].key, 'owned');
assert.equal(sections[1].assets.length, 1);
assert.equal(overlappingSupplierSources([supplier], [{ items: [{ asset: 2 }] }]), true);
assert.equal(overlappingSupplierSources([{ ...supplier, id: 'group', ids: [2, 3] }], [{ items: [{ asset: 3 }] }]), true);
assert.equal(overlappingSupplierSources([supplier], [{ items: [{ asset: 4 }] }]), false);
console.log('21 inventory helper checks passed.');
